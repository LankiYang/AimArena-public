// UTF-8. Exact triangle collision for the published Ascent B GLB excerpt.
// Rendering and collision share the same original 192,209 triangles; no box proxy.
import * as THREE from 'three';
import { Octree } from 'three/addons/math/Octree.js';
import { Capsule } from 'three/addons/math/Capsule.js';

export const ASCENT_SPAWNS = Object.freeze({
  bMain: { foot: [-23, 1, -50], yaw: -10 * Math.PI / 180, source: 'upstream initAscentB()' },
  ct: { foot: [-6, 1.003, -88], yaw: -156 * Math.PI / 180, source: 'upstream CT Arch floor probe' },
});

// This intentionally parses only the uncompressed single-mesh GLB generated by
// research/convert-ascent.cjs. Unexpected formats fail rather than lose surfaces.
export function parseAscentGLB(input) {
  const bytes = input instanceof ArrayBuffer ? new Uint8Array(input) : new Uint8Array(input.buffer, input.byteOffset, input.byteLength);
  const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  if (bytes.length < 28 || dv.getUint32(0, true) !== 0x46546c67 || dv.getUint32(4, true) !== 2 || dv.getUint32(8, true) !== bytes.length) throw new Error('Invalid or truncated Ascent GLB');
  let gltf, bin, offset = 12;
  while (offset < bytes.length) {
    const length = dv.getUint32(offset, true), type = dv.getUint32(offset + 4, true);
    if (offset + 8 + length > bytes.length) throw new Error('Truncated GLB chunk');
    if (type === 0x4e4f534a) gltf = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes.subarray(offset + 8, offset + 8 + length)));
    if (type === 0x004e4942) bin = bytes.subarray(offset + 8, offset + 8 + length);
    offset += 8 + length;
  }
  if (!gltf || !bin || gltf.meshes.length !== 1 || gltf.meshes[0].primitives.length !== 1 || gltf.extensionsRequired?.length) throw new Error('Unsupported Ascent GLB structure');
  const p = gltf.meshes[0].primitives[0], data = new DataView(bin.buffer, bin.byteOffset, bin.byteLength);
  const shapes = { SCALAR: 1, VEC3: 3, VEC4: 4 }, types = { 5121: { bytes: 1, array: Uint8Array, get: 'getUint8' }, 5125: { bytes: 4, array: Uint32Array, get: 'getUint32' }, 5126: { bytes: 4, array: Float32Array, get: 'getFloat32' } };
  function read(index) {
    const a = gltf.accessors[index], view = gltf.bufferViews[a?.bufferView], format = types[a?.componentType], n = shapes[a?.type];
    if (!a || !view || !format || !n || a.sparse) throw new Error('Unsupported Ascent accessor');
    const start = (view.byteOffset || 0) + (a.byteOffset || 0), stride = view.byteStride || format.bytes * n;
    if (start + (a.count - 1) * stride + format.bytes * n > bin.length) throw new Error('Ascent accessor out of bounds');
    const out = new format.array(a.count * n);
    for (let i = 0; i < a.count; i++) for (let c = 0; c < n; c++) {
      const v = data[format.get](start + i * stride + c * format.bytes, true);
      if (!Number.isFinite(v)) throw new Error('Non-finite Ascent vertex');
      out[i * n + c] = v;
    }
    return new THREE.BufferAttribute(out, n, Boolean(a.normalized));
  }
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute('position', read(p.attributes.POSITION));
  geometry.setAttribute('normal', read(p.attributes.NORMAL));
  geometry.setAttribute('color', read(p.attributes.COLOR_0));
  geometry.setIndex(read(p.indices));
  for (const i of geometry.index.array) if (i >= geometry.attributes.position.count) throw new Error('Ascent index out of bounds');
  geometry.computeBoundingBox(); geometry.computeBoundingSphere();
  return { geometry, metadata: gltf.asset.extras, vertexCount: geometry.attributes.position.count, triangleCount: geometry.index.count / 3 };
}

// Three's example Octree has a fixed 16-level subdivision and assumes triangle
// winding. Bounded depth limits build cost; both face orientations are queried.
// Every original triangle remains present. The caps affect indexing, not detail.
class SurfaceOctree extends Octree {
  constructor(box, options = {}) { super(box); this.maxDepth = options.maxDepth ?? 9; this.leafSize = options.leafSize ?? 48; }
  split(level = 0) {
    if (!this.box || this.triangles.length <= this.leafSize || level >= this.maxDepth) return this;
    const half = this.box.getSize(new THREE.Vector3()).multiplyScalar(.5), children = [];
    for (let x = 0; x < 2; x++) for (let y = 0; y < 2; y++) for (let z = 0; z < 2; z++) {
      const min = this.box.min.clone().add(new THREE.Vector3(x, y, z).multiply(half));
      children.push(new SurfaceOctree(new THREE.Box3(min, min.clone().add(half)), this));
    }
    for (const triangle of this.triangles) for (const child of children) if (child.box.intersectsTriangle(triangle)) child.triangles.push(triangle);
    this.triangles.length = 0;
    for (const child of children) if (child.triangles.length) { child.split(level + 1); this.subTrees.push(child); }
    return this;
  }
  collect(predicate, triangles) {
    const seen = new Set(triangles);
    const visit = tree => { if (tree.box && !predicate(tree.box)) return; for (const triangle of tree.triangles) if (!seen.has(triangle)) { seen.add(triangle); triangles.push(triangle); } for (const sub of tree.subTrees) visit(sub); };
    visit(this); return triangles;
  }
  getCapsuleTriangles(capsule, triangles) { return this.collect(box => capsule.intersectsBox(box), triangles); }
  getRayTriangles(ray, triangles) { return this.collect(box => ray.intersectsBox(box), triangles); }
  triangleCapsuleIntersect(capsule, triangle) {
    const normal = triangle.getNormal(new THREE.Vector3()), center = capsule.getCenter(new THREE.Vector3());
    const face = normal.dot(center.sub(triangle.a)) < 0 ? new THREE.Triangle(triangle.a, triangle.c, triangle.b) : triangle;
    return super.triangleCapsuleIntersect(capsule, face);
  }
  rayIntersect(ray, maxDistance = Infinity, floorOnly = false) {
    if (ray.direction.lengthSq() === 0) return false;
    const candidates = this.getRayTriangles(ray, []), hit = new THREE.Vector3(); let best = false, distance = maxDistance;
    for (const triangle of candidates) {
      const normal = triangle.getNormal(new THREE.Vector3());
      if (floorOnly && Math.abs(normal.y) < .6) continue;
      if (ray.intersectTriangle(triangle.a, triangle.b, triangle.c, false, hit)) {
        const d = hit.distanceTo(ray.origin);
        if (d <= distance) { distance = d; best = { position: hit.clone(), triangle, distance: d, normal: normal.dot(ray.direction) > 0 ? normal.negate() : normal }; }
      }
    }
    return best;
  }
}

export function buildAscentCollision(input, options = {}) {
  const started = performance.now(), parsed = parseAscentGLB(input), parsedAt = performance.now();
  const mesh = new THREE.Mesh(parsed.geometry, new THREE.MeshStandardMaterial({ color: '#c5c4bc', vertexColors: true, roughness: .95, side: THREE.DoubleSide }));
  mesh.name = 'Ascent B exact source geometry'; mesh.receiveShadow = true;
  const octree = new SurfaceOctree(undefined, options).fromGraphNode(mesh);
  let nodes = 0, leaves = 0, refs = 0, depth = 0;
  (function count(tree, level) { nodes++; depth = Math.max(depth, level); if (!tree.subTrees.length) leaves++; refs += tree.triangles.length; tree.subTrees.forEach(t => count(t, level + 1)); })(octree, 0);
  const stats = { vertexCount: parsed.vertexCount, triangleCount: parsed.triangleCount, parseMs: parsedAt - started, buildMs: performance.now() - parsedAt, nodes, leaves, triangleReferences: refs, maxDepth: depth };
  const down = new THREE.Vector3(0, -1, 0);
  return { mesh, geometry: parsed.geometry, octree, metadata: parsed.metadata, stats,
    floorAt(x, z, fromY = 4, maxDrop = 8) { return octree.rayIntersect(new THREE.Ray(new THREE.Vector3(x, fromY, z), down), maxDrop, true); },
    raycast(origin, direction, maxDistance = 150) { return octree.rayIntersect(new THREE.Ray(origin.clone(), direction.clone().normalize()), maxDistance); },
    dispose() { octree.clear(); mesh.geometry.dispose(); mesh.material.dispose(); },
  };
}

export async function loadAscentCollision(url = '/assets/maps/ascent-b.glb', options = {}) {
  const response = await fetch(url); if (!response.ok) throw new Error(`Ascent GLB HTTP ${response.status}`);
  return buildAscentCollision(await response.arrayBuffer(), options);
}

export class AscentWalker {
  constructor(world, spawn = ASCENT_SPAWNS.bMain.foot) { this.world = world; this.radius = .32; this.height = 1.8; this.eyeHeight = 1.62; this.velocity = new THREE.Vector3(); this.capsule = new Capsule(); this.grounded = false; this.fellOut = false; this.crouched = false; this.reset(spawn); }
  reset(foot = ASCENT_SPAWNS.bMain.foot) { const p = Array.isArray(foot) ? new THREE.Vector3(...foot) : foot; this.capsule.set(p.clone().add(new THREE.Vector3(0, this.radius + .01, 0)), p.clone().add(new THREE.Vector3(0, this.height - this.radius + .01, 0)), this.radius); this.velocity.set(0, 0, 0); this.fellOut = false; return this; }
  getFoot(target = new THREE.Vector3()) { return target.copy(this.capsule.start).add(new THREE.Vector3(0, -this.radius, 0)); }
  getEye(target = new THREE.Vector3()) { return this.getFoot(target).add(new THREE.Vector3(0, this.eyeHeight, 0)); }
  canStand() {
    if (!this.crouched) return true;
    // Test the newly occupied head volume against original triangles. Checking
    // only this extension avoids treating the resting floor as a blocked head.
    const end = this.capsule.end.clone(); end.y += 1.8 - this.height;
    const head = new Capsule(this.capsule.end.clone(), end, this.radius);
    const hit = this.world.octree.capsuleIntersect(head);
    return !hit || hit.depth < .002;
  }
  update(direction, dt, { jump = false, crouch = this.crouched, speed = 5.4 } = {}) {
    dt = Math.max(0, Math.min(.05, dt));
    if (!crouch && this.crouched && !this.canStand()) crouch = true;
    if (crouch !== this.crouched) { const delta = (crouch ? 1.18 : 1.8) - this.height; this.height += delta; this.capsule.end.y += delta; this.crouched = crouch; this.eyeHeight = crouch ? 1.04 : 1.62; }
    if (jump && this.grounded) { this.velocity.y = 6.2; this.grounded = false; }
    const input = new THREE.Vector3(direction.x, 0, direction.z); if (input.lengthSq() > 1) input.normalize();
    this.velocity.x = input.x * speed; this.velocity.z = input.z * speed;
    const steps = Math.max(1, Math.ceil((this.velocity.length() + 25 * dt) * dt / (this.radius * .35))), subdt = dt / steps;
    for (let s = 0; s < steps; s++) {
      const stepHeight = this.world.stepHeight, wasGrounded = this.grounded;
      if (stepHeight && wasGrounded && input.lengthSq()) {
        const foot = this.getFoot(), x = foot.x + this.velocity.x * subdt, z = foot.z + this.velocity.z * subdt;
        const step = this.world.floorAt(x,z,foot.y+stepHeight,stepHeight+.32,this.radius*.93);
        if (step && step.position.y > foot.y + .002) {
          const dy = step.position.y - foot.y + .001, moved = this.capsule.clone();
          moved.translate(new THREE.Vector3(x-foot.x,dy,z-foot.z));
          if (!this.world.octree.capsuleIntersect(moved)) this.capsule.translate(new THREE.Vector3(0,dy,0));
        }
      }
      this.velocity.y -= 25 * subdt; this.capsule.translate(this.velocity.clone().multiplyScalar(subdt)); this.grounded = false;
      for (let iteration = 0; iteration < 4; iteration++) {
        const result = this.world.octree.capsuleIntersect(this.capsule); if (!result || result.depth < 1e-7) break;
        if (result.normal.y > .55) this.grounded = true;
        this.capsule.translate(result.normal.clone().multiplyScalar(result.depth + 1e-5));
        const into = this.velocity.dot(result.normal); if (into < 0) this.velocity.addScaledVector(result.normal, -into);
      }
      if (stepHeight && wasGrounded && !this.grounded && this.velocity.y <= 0) {
        const foot = this.getFoot(), floor = this.world.floorAt(foot.x,foot.z,foot.y,.32);
        if (floor) {
          this.capsule.translate(new THREE.Vector3(0,floor.position.y-foot.y+.00001,0));
          this.grounded = true; this.velocity.y = 0;
        }
      }
    }
    this.fellOut = this.capsule.start.y < this.world.geometry.boundingBox.min.y - 8;
    return this.getFoot();
  }
}
